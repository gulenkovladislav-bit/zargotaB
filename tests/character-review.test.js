'use strict';
const assert = require('node:assert/strict');
const R = require('../character-review.js');
const base = {id:1, name:'Hero', stats:{str:{cur:2}, dex:{cur:1}}, inventoryItems:[{itemId:'a',name:'Sword',qty:1}], skills:[{_syncId:'s',name:'Skill',description:'Old'}]};
const copy = () => R.clone(base);
let player=copy(),master=copy();player.stats.str.cur=3;master.stats.dex.cur=4;
let changes=R.diff(base,player), result=R.apply(master,changes);
assert.equal(result.character.stats.str.cur,3);assert.equal(result.character.stats.dex.cur,4);
master.stats.str.cur=5;assert.equal(R.apply(master,changes).ok,false);
assert.equal(R.apply(master,changes,{0:'take'}).character.stats.str.cur,3);
assert.equal(R.apply(master,changes,{0:'keep'}).character.stats.str.cur,5);
const reviewed=R.analyze(master,changes).map(r=>r.current);master.stats.str.cur=7;
assert.equal(R.apply(master,changes,{0:'take'},reviewed).ok,false,'a stale choice cannot overwrite newer master edits');
player=copy();master=copy();player.inventoryItems.push({itemId:'b',name:'Potion',qty:1});master.inventoryItems[0].qty=2;
result=R.apply(master,R.diff(base,player));assert.equal(result.character.inventoryItems.length,2);assert.equal(result.character.inventoryItems[0].qty,2);
assert.deepEqual(R.apply(result.character,R.diff(base,player)).character,result.character,'redelivery is idempotent');
player=copy();master=copy();player.skills[0].description='New';master.skills.push({_syncId:'t',name:'Other'});
assert.equal(R.apply(master,R.diff(base,player)).character.skills.length,2);
player=copy();master=copy();player.inventoryItems=[];master.inventoryItems[0].qty=2;
assert.equal(R.apply(master,R.diff(base,player)).ok,false,'delete vs changed item requires decision');
player=copy();master=copy();player.inventoryItems[0].qty=2;master.inventoryItems=[];
assert.equal(R.apply(master,R.diff(base,player),{0:'take'}).ok,false,'cannot silently resurrect a removed parent');
assert.deepEqual(R.rebase(base,player,master).character,player,'deleted remote parent preserves local draft');
player=copy();master=copy();player.stats.str.cur=3;master.stats.dex.cur=4;
let rebased=R.rebase(base,player,master);assert.equal(rebased.character.stats.dex.cur,4);assert.equal(rebased.character.stats.str.cur,3);assert.equal(R.diff(rebased.base,rebased.character).length,1);
master.stats.str.cur=8;rebased=R.rebase(base,player,master);assert.equal(rebased.base.stats.str.cur,2);assert.equal(rebased.character.stats.str.cur,3);assert.equal(rebased.character.stats.dex.cur,4);
const second=R.diff(base,{...base,name:'Second'});const first=R.apply(base,R.diff(base,{...base,name:'First'}));assert.equal(R.apply(first.character,second).ok,false,'two requests for one field conflict');
assert.equal(R.diff(base,{...base,revision:44,updatedAt:900}).length,0);
assert.equal(R.equal({a:1,b:2},{b:2,a:1}),true);
assert.throws(()=>R.apply({},[{path:['__proto__','polluted'],before:{exists:false},after:{exists:true,value:1}}],{0:'take'}),/invalid-path/);
assert.equal({}.polluted,undefined);
let id=0;const prepared=R.prepare({skills:[{name:'A'},{name:'A'}]},()=>String(++id));assert.notEqual(prepared.skills[0]._syncId,prepared.skills[1]._syncId);
assert.deepEqual(R.prepare(prepared,()=>String(++id)),prepared,'stable IDs survive edits and saves');
console.log('character-review: disjoint edits, conflicts, concurrent review, lists, retries, rebase and identity passed');
