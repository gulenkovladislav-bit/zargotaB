'use strict';
const assert=require('node:assert/strict');
const N=require('../character-update-notices.js');
const before={id:1,stats:{str:{cur:1},dex:{cur:2}},hpCur:14,inventoryItems:[],portrait:'data:image/png;base64,OLD'};
const after={...before,stats:{str:{cur:3},dex:{cur:2}},hpCur:10,inventoryItems:[{itemId:'key',name:'Ключ',qty:1,image:'data:image/png;base64,SECRET'}],portrait:'data:image/png;base64,NEW',revision:3};
const changes=N.summary(before,after);
assert.deepEqual(changes.map(r=>r.field),['stats.str','hpCur','inventoryItems','portrait']);
assert.deepEqual(changes[0],{field:'stats.str',label:['Сила','Сила'],before:'1',after:'3'});
assert.deepEqual(changes[2].added,['Ключ']);
assert.ok(!JSON.stringify(changes).includes('base64'),'history stores bounded descriptions, not images or entire sheets');
assert.deepEqual(N.summary(before,{...before,revision:9,updatedAt:50,updatedBy:'gm',source:'room'}),[],'metadata alone is not an update');
let event={characterId:1,before,after,channel:'cloud',revision:'sheet:2',author:'master',status:'pending'};
let rows=N.record([],event,10);
assert.equal(rows[0].status,'pending');
assert.strictEqual(N.record(rows,event,20),rows,'repeated snapshots do not repeat the notice');
rows=N.record(rows,{...event,status:'applied'},30);
assert.equal(rows.length,1);assert.equal(rows[0].status,'applied','applying the pending revision replaces its waiting notice');
rows[0].read=true;
assert.strictEqual(N.record(rows,{...event,status:'applied'},40),rows,'replayed snapshots cannot make read updates unread');
assert.strictEqual(N.record(rows,{...event,revision:3,own:true},40),rows,'own room echoes do not notify');
rows=N.record(rows,{...event,revision:3},40);rows=N.record(rows,{...event,revision:4},50);
assert.equal(rows.filter(r=>r.status==='pending').length,1,'newer pending revision replaces an outdated pending notice');
for(let i=5;i<30;i++)rows=N.record(rows,{...event,status:'applied',revision:i},i);
assert.equal(rows.length,12,'local history is bounded');
assert.equal(N.summary(before,{...before,inventoryItems:[{itemId:'x',name:'<img onerror=alert(1)>',qty:1}]}).find(r=>r.field==='inventoryItems').added[0],'<img onerror=alert(1)>','model retains text for escaped UI rendering');
console.log('character updates: actual changes, deduplication, own echoes, pending/applied states, bounded history passed');
const bleed={id:100,type:'status',statusKey:'bleed',label:'Кровотечение',unit:'rounds',remaining:3,stacks:1};
const state={tempEffects:[bleed],statuses:['bleed']};
assert.deepEqual(N.statusGrants({},state),[bleed],'effect plus legacy flag is one grant');
assert.deepEqual(N.statusGrants(state,{...state,tempEffects:[{...bleed,remaining:2}]}),[],'round ticks do not announce grants');
assert.deepEqual(N.statusGrants(state,{}),[],'removals do not announce grants');
assert.equal(N.statusGrants(state,{...state,tempEffects:[{...bleed,stacks:2}]}).length,1,'increased bleed stack is a grant');
assert.equal(N.statusGrants(state,{...state,tempEffects:[{...bleed,id:101}]}).length,1,'replacement effect announces once');
assert.deepEqual(N.statusGrants({statuses:['bleed']},state),[],'normalization of a legacy marker is not a grant');
assert.deepEqual(N.statusGrants({}, {tempEffects:[{id:5,type:'hp',value:3}]}),[],'other temporary effects are excluded');
assert.deepEqual(N.contentChanges(before,{...before,hpCur:2,speed:4,ac:20}),[],'numerical changes do not light content indicator');
assert.ok(N.contentChanges(before,after).some(r=>r.field==='inventoryItems'));
assert.ok(!N.contentChanges(before,after).some(r=>r.field==='hpCur'||r.field.startsWith('stats.')));
assert.deepEqual(N.contentChanges(state,{...state,tempEffects:[{...bleed,remaining:2}]}),[],'countdown does not light content indicator');
assert.ok(N.contentChanges({}, {family:[{id:1,name:'Friend'}]}).some(r=>r.field==='family'));
