prior.players[0].bet=3;prior.players[0].contributed=8;
prior.players[1].bet=7;prior.players[1].contributed=12;
prior.players[2].folded=true;prior.target=7;
assert.equal(rules.raiseLimit(prior),20,'includes previous contributions, excludes folded rich players');
assert(rules.act(prior,'allin'));assert.equal(prior.players[0].lastBet.added,24);assert.equal(prior.players[0].stack,26);
