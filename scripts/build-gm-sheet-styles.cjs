'use strict';
// Ship the phone CSS as data too: file:// forbids reading linked CSSOM rules.
// These are generated inputs, not a separately maintained UI stylesheet.
const fs=require('node:fs'),path=require('node:path');
const root=path.resolve(__dirname,'..');
const sources=['character-mobile-overview.css','character-mobile-skills.css','character-mobile-inventory.css','character-mobile-lore.css','character-spell-detail.css'];
const css=sources.map(name=>'/* '+name+' */\n'+fs.readFileSync(path.join(root,name),'utf8')).join('\n');
const output='/* Generated by scripts/build-gm-sheet-styles.cjs. Edit the mobile CSS sources. */\nwindow.ZargotaGmSheetStyles='+JSON.stringify(css)+';\n';
const target=path.join(root,'gm-sheet-styles.js');
if(process.argv.includes('--check')){
 if(!fs.existsSync(target)||fs.readFileSync(target,'utf8')!==output)throw new Error('Run node scripts/build-gm-sheet-styles.cjs after editing mobile styles');
}else fs.writeFileSync(target,output);
