const assert = require('node:assert/strict');
const fs = require('node:fs');
const vm = require('node:vm');
const path = require('node:path');
const base = path.resolve(__dirname, '..');
const e = require('../story-content/evan/episode-1-courtyard-v11.json').episode;
const ctx = { window: {}, setTimeout, clearTimeout };
vm.createContext(ctx);
for (const f of ['story-quests.js', 'story-quest-actions.js', 'story-environment.js', 'story-items.js']) vm.runInContext(fs.readFileSync(path.join(base, f), 'utf8'), ctx);
const { ZargotaStoryQuests: quests, ZargotaStoryEnvironment: environment, ZargotaStoryQuestActions: actions, ZargotaStoryItems: items } = ctx.window;
const streetId = 'scene-mu7f8tk1-6m4a';
const street = e.scenes.find(s => s.id === streetId).scene;
const qstate = { active: 'evan-walk-quest', done: [], actionObjects: {} };
const gate = scene => scene.story.zones.find(z => z.id === 'evan-green-entrance');
assert.ok(!street.tokens.some(t => t.id === 'evan-green-entrance'), 'Old click token removed');
const before = gate(quests.gatedScene(e, street, streetId, qstate));
assert.equal(before.enabled, false);
assert.equal(environment.entered([before], { x: before.x, y: before.y }, { inside: {}, fired: {} }, {}).length, 0);
const walk = e.quests.find(q => q.id === qstate.active);
assert.equal(walk.milestones[0].minCompleted, 2);
assert.equal(new Set(walk.milestones[0].dialogueIds).size, 3);
assert.equal(quests.complete(e, qstate, 'evan-walk-pottery'), null);
assert.equal(quests.complete(e, qstate, 'evan-walk-done').id, walk.id);
assert.equal(qstate.active, 'evan-yard-meet-quest');
actions.run(walk.actions, { state: qstate, records: e.scenes, redraw() {} }, () => {});
const after = gate(quests.gatedScene(e, street, streetId, qstate));
assert.equal(after.enabled, true);
assert.equal(after.mode, 'enter');
assert.equal(after.marker, '!');
assert.equal(after.markerVisible, true);
assert.equal(after.sceneId, 'scene-evan-green-courtyard');
const memory = { inside: {}, fired: {} };
assert.equal(environment.entered([after], { x: after.x, y: after.y }, memory, {}).length, 1, 'Walking into gate works without click ID');
assert.equal(environment.entered([after], { x: after.x, y: after.y }, memory, {}).length, 0, 'No repeat while standing inside');
environment.entered([after], { x: 0, y: 0 }, memory, {});
assert.equal(environment.entered([after], { x: after.x, y: after.y }, memory, {}).length, 1, 'Return visits work');
assert.ok(!street.story.walkable);
assert.ok(!street.story.zones.some(z => z.blocked), 'No added walls');
const item = e.storyItems.find(i => i.itemId === 'evan-draft-folder');
const c = { inventoryItems: [] };
items.award(c, item, 1, false);
items.award(c, item, 1, false);
assert.equal(c.inventoryItems.length, 1);
assert.equal(c.inventoryItems[0].qty, 1);
assert.equal(c.inventoryItems[0].equipped, false);
assert.equal(c.inventoryItems[0].inspectImage, item.inspectImage);
const node = id => e.nodes.find(n => n.id === id);
assert.equal(node('evan-draft-folder-take').afterEffect, 'evan-has-drafts');
assert.equal(node('evan-leor-hello').links.find(l => l.to === 'evan-leor-design').requires, 'evan-has-drafts');
assert.ok(!node('evan-yard-wheel').image);
assert.ok(node('evan-green-rules').image.endsWith('stones-v1.png'));
assert.equal(node('evan-shop-open').cameraEvent.y, 46, 'Camera return retained');
for (const n of e.nodes.filter(n => /draft-folder|leor-design|walk-pottery/.test(n.id))) {
  for (const p of [n, ...n.slides]) assert.ok(p.text && p.textUk);
}
for (const n of e.nodes) if (n.image) assert.ok(fs.existsSync(path.join(base, decodeURIComponent(n.image))), n.image);
console.log('PASS: gated entry without click, return visits, optional unique folder, bilingual dialogue, images and camera retained. Source/runtime mocks only.');
